// tokens.json -> dist/tokens.css (custom properties) + dist/tokens.js/.d.ts
// Generated from the Figma variables. Do not hand-edit tokens.json.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

type Tree = { [key: string]: string | Tree };

const here = new URL(".", import.meta.url);
const tree = JSON.parse(
  readFileSync(new URL("tokens.json", here), "utf8"),
) as Tree;

const flat: [name: string, value: string][] = [];
(function walk(node: Tree, path: string[]) {
  for (const [key, value] of Object.entries(node)) {
    if (typeof value === "string") {
      flat.push([`--${[...path, key].join("-")}`, value]);
    } else {
      walk(value, [...path, key]);
    }
  }
})(tree, []);

const dist = new URL("../dist/", here);
mkdirSync(dist, { recursive: true });

const css = [
  "/* Generated by tokens/build.ts. Do not edit. */",
  ":root {",
  "  color-scheme: dark;",
  ...flat.map(([name, value]) => `  ${name}: ${value};`),
  "}",
  "",
].join("\n");
writeFileSync(new URL("tokens.css", dist), css);

const entries = flat.map(([name, value]) => [name.slice(2), value]);
const js = `export const tokens = ${JSON.stringify(
  Object.fromEntries(entries),
  null,
  2,
)};

/** CSS variable reference, for example \`token("colour-accent")\`. */
export const token = (name) => \`var(--\${name})\`;
`;
writeFileSync(new URL("tokens.js", dist), js);

const names = entries.map(([n]) => JSON.stringify(n)).join(" | ");
writeFileSync(
  new URL("tokens.d.ts", dist),
  `export type TokenName = ${names};
export declare const tokens: Record<TokenName, string>;
export declare const token: (name: TokenName) => string;
`,
);
writeFileSync(
  new URL("fonts.css", dist),
  `${[400, 500, 600]
    .map((w) => `@import "@fontsource/geist/latin-${w}.css";`)
    .concat(
      [400, 500].map((w) => `@import "@fontsource/geist-mono/latin-${w}.css";`),
    )
    .join("\n")}\n`,
);
console.log(`tokens: ${flat.length} variables`);
